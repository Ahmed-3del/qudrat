export type QuestionSeed = {
  prompt: string;
  options: string[];
  answer: number;
  solution: string;
};

export type Question = QuestionSeed & {
  id: string;
  lessonId: string;
  sourcePage: number;
};

export type Lesson = {
  id: string;
  title: string;
  subtitle: string;
  questions: Question[];
};

export type Door = {
  id: number;
  title: string;
  label: string;
  summary: string;
  lessons: Lesson[];
};

const makeLesson = (
  doorId: number,
  lessonIndex: number,
  title: string,
  subtitle: string,
  seeds: QuestionSeed[],
): Lesson => {
  const id = `door-${doorId}-lesson-${lessonIndex}`;
  return {
    id,
    title,
    subtitle,
    questions: seeds.map((seed, questionIndex) => ({
      ...seed,
      id: `d${doorId}-l${lessonIndex}-q${questionIndex + 1}`,
      lessonId: id,
      sourcePage: doorId * 100 + lessonIndex * 10 + questionIndex + 1,
    })),
  };
};

const q = (prompt: string, options: string[], answer: number, solution: string): QuestionSeed => ({ prompt, options, answer, solution });

